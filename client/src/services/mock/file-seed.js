/**
 * The drive, as MongoDB would hold it.
 *
 * One flat collection with `parentId` pointers rather than a nested tree, which
 * is how this has to be stored: a tree document has no way to page a folder, no
 * way to index `updatedAt` across the whole drive, and a 16MB ceiling. Every
 * query the UI makes — a folder's contents, everything starred, everything in
 * the trash — is one indexed find over this array.
 *
 * Every value is raw. `size` is bytes, not "4.2 MB"; `updatedAt` is ISO, not
 * "2 hours ago". Pre-formatted strings cannot be sorted, and sorting is the
 * whole point of a file browser. Formatting happens at render, in `lib/format`.
 *
 * Dates are fixed literals rather than offsets from `Date.now()`. A fixture that
 * computes its own timestamps produces different data on the server and in the
 * browser, which is a hydration mismatch waiting for the first person who leaves
 * a tab open over midnight.
 *
 * Fields that look redundant are the ones a real backend denormalises:
 *
 * - `itemCount` on folders — counting children on every render is a query per
 *   row; Mongo keeps a counter and updates it on write.
 * - `kind` — stored so the filter can use an index rather than scanning MIME
 *   types in application code.
 * - `storageKey` — the S3 object key, never a URL. Presigned URLs expire, so an
 *   entity that carries one is a bug with a timer on it. See `getDownloadUrl`.
 */

